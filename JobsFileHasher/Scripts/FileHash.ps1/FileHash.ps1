function Get-JobsFileHashTarget {
    param([Parameter(Mandatory = $true)][string]$Target)
    $item = Get-Item -LiteralPath $Target -Force -ErrorAction Stop
    if ($item.PSProvider.Name -ne 'FileSystem' -or $item.PSIsContainer -or
        ($item.Attributes -band ([IO.FileAttributes]::ReparsePoint -bor [IO.FileAttributes]::Device)) -ne 0) {
        throw '文件指纹只接受一个普通文件；不接受目录、链接或设备。'
    }
    return $item
}

function ConvertTo-JobsFileHashSafeText {
    param([AllowEmptyString()][string]$Text)
    return [regex]::Replace($Text, '[\x00-\x1f\x7f-\x9f\u202a-\u202e\u2066-\u2069]', {
        param($match)
        return ('\u{0:X4}' -f [int][char]$match.Value[0])
    })
}

function Get-JobsFileFingerprint {
    param([Parameter(Mandatory = $true)][string]$Target)
    $item = Get-JobsFileHashTarget $Target
    $stream = $null
    $digest = $null
    try {
        # 读共享允许其它读取者，Windows 上排除并发写入和替换。
        $stream = [IO.File]::Open($item.FullName, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::Read)
        [void](Get-JobsFileHashTarget $item.FullName)
        $digest = [Security.Cryptography.SHA256]::Create()
        $hash = [BitConverter]::ToString($digest.ComputeHash($stream)).Replace('-', '').ToLowerInvariant()
        if ($hash -cnotmatch '^[0-9a-f]{64}$') { throw 'SHA-256 结果无效，未更新剪贴板。' }
        return [pscustomobject]@{ Path = $item.FullName; Bytes = $stream.Length; Algorithm = 'SHA-256'; Hash = $hash }
    } finally {
        if ($null -ne $digest) { $digest.Dispose() }
        if ($null -ne $stream) { $stream.Dispose() }
    }
}

function Set-JobsFileHashClipboard {
    param([Parameter(Mandatory = $true)][string]$Hash)
    if ($Hash -cnotmatch '^[0-9a-f]{64}$') { throw '拒绝复制无效 SHA-256。' }
    if ([Environment]::OSVersion.Platform -ne [PlatformID]::Win32NT) { throw '系统剪贴板仅支持 Windows 桌面。' }
    if ([Threading.Thread]::CurrentThread.ApartmentState -ne 'STA') { throw '请通过右键菜单或 powershell.exe -STA 使用系统剪贴板。' }
    Add-Type -AssemblyName System.Windows.Forms
    # 系统剪贴板可能短暂被占用；有限重试后明确失败，终端仍保留摘要。
    for ($attempt = 0; $attempt -lt 5; $attempt++) {
        try {
            [Windows.Forms.Clipboard]::SetText($Hash, [Windows.Forms.TextDataFormat]::UnicodeText)
            return
        } catch {
            if ($attempt -eq 4) { throw 'SHA-256 已计算，但系统剪贴板被占用或不可用，复制失败；请从终端手动复制。' }
            Start-Sleep -Milliseconds 150
        }
    }
}

function Invoke-JobsFileHash {
    [CmdletBinding()]
    param([Parameter(Mandatory = $true)][string]$Target)
    Write-Host 'Jobs · 查看文件指纹 Hash（SHA-256）' -ForegroundColor Red
    Write-Host '只读计算一个文件；完成后自动复制纯摘要。不修改或运行文件，Ctrl+C 随时中止。'
    $item = Get-JobsFileHashTarget $Target
    Write-Host ('文件：' + (ConvertTo-JobsFileHashSafeText $item.FullName))
    Write-Host '正在计算 SHA-256，请稍候…'
    $result = Get-JobsFileFingerprint $item.FullName
    Write-Host ('大小：{0} 字节' -f $result.Bytes)
    Write-Host ('SHA-256：' + $result.Hash) -ForegroundColor Green
    Set-JobsFileHashClipboard $result.Hash
    Write-Host '✔ SHA-256 已复制到系统剪贴板（不含文件名或换行）。' -ForegroundColor Green
}

