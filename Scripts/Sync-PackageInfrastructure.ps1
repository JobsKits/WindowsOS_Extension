    if (-not (Test-Path -LiteralPath $panelDestination -PathType Leaf) -or
        (Get-FileHash -LiteralPath $panelSource).Hash -ne (Get-FileHash -LiteralPath $panelDestination).Hash) {
        $different += ($folder.Name + '/SelectionPanel.psm1')
